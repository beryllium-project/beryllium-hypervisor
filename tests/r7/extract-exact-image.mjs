const ELF_MAGIC = Buffer.from([0x7f, 0x45, 0x4c, 0x46])
const ELFCLASS64 = 2
const ELFDATA2LSB = 1
const ET_EXEC = 2
const EM_RISCV = 243
const SHT_SYMTAB = 2
const SHT_STRTAB = 3
const SHT_NOBITS = 8
const SHF_ALLOC = 0x2
const SHF_EXECINSTR = 0x4
const SHF_COMPRESSED = 0x800
const SHN_UNDEF = 0
const SHN_LORESERVE = 0xff00

const OPCODE_JAL = 0x6f
const OPCODE_JALR = 0x67
const OPCODE_BRANCH = 0x63
const OPCODE_AUIPC = 0x17

const MAX_SAFE = BigInt(Number.MAX_SAFE_INTEGER)

const safeNumber = (value, context) => {
  if (value < 0n || value > MAX_SAFE) throw new Error(`${context} is out of the supported range`)
  return Number(value)
}

// Every address, size, flag word, and raw unit is printed here, so it must
// not narrow: `>>> 0` truncated anything at or above 2^32 (0x102006aa0
// printed as 0x02006aa0). Values below 2^32 print exactly as before, and
// anything that is not a non-negative safe integer is refused, not wrapped.
const hex = (value, digits) => {
  if (!Number.isSafeInteger(value) || value < 0)
    throw new Error(`value ${value} is not a non-negative safe integer`)
  return `0x${value.toString(16).padStart(digits, '0')}`
}

const readCString = (buffer, sectionOffset, sectionSize, nameOffset, context) => {
  if (nameOffset < 0 || nameOffset >= sectionSize) throw new Error(`${context} name offset is out of range`)
  const start = sectionOffset + nameOffset
  const limit = sectionOffset + sectionSize
  let end = start
  while (end < limit && buffer[end] !== 0) end += 1
  if (end >= limit) throw new Error(`${context} name is not NUL-terminated (truncated string table)`)
  return buffer.toString('latin1', start, end)
}

// Extract the bit field inst[hi:lo] as an unsigned value.
const fieldBits = (word, hi, lo) => {
  const width = hi - lo + 1
  const mask = width >= 32 ? 0xffffffff : (1 << width) - 1
  return (word >>> lo) & mask
}

// Sign-extend an unsigned `bits`-wide two's-complement value held in a JS
// int32. Left-shifting the value into bit 31 and arithmetic-right-shifting
// it back out restores the sign correctly for the widths used here (<=21).
const signExtend = (value, bits) => {
  const shift = 32 - bits
  return (value << shift) >> shift
}

const decodeJalImmediate = (word) => {
  const bit20 = fieldBits(word, 31, 31)
  const bits10to1 = fieldBits(word, 30, 21)
  const bit11 = fieldBits(word, 20, 20)
  const bits19to12 = fieldBits(word, 19, 12)
  const imm = (bit20 << 20) | (bits19to12 << 12) | (bit11 << 11) | (bits10to1 << 1)
  return signExtend(imm, 21)
}

const decodeBranchImmediate = (word) => {
  const bit12 = fieldBits(word, 31, 31)
  const bits10to5 = fieldBits(word, 30, 25)
  const bits4to1 = fieldBits(word, 11, 8)
  const bit11 = fieldBits(word, 7, 7)
  const imm = (bit12 << 12) | (bit11 << 11) | (bits10to5 << 5) | (bits4to1 << 1)
  return signExtend(imm, 13)
}

const decodeItypeImmediate = (word) => signExtend(fieldBits(word, 31, 20), 12)

// The U-type immediate already occupies bits 31:12 with bits 11:0 zero, and
// JS `&` always yields a signed int32, so this is already the correctly
// signed byte value `auipc` adds to its own address.
const decodeUtypeImmediate = (word) => word & 0xfffff000

const rdField = (word) => fieldBits(word, 11, 7)
const rs1Field = (word) => fieldBits(word, 19, 15)

// Walk a symbol's raw bytes into an ordered sequence of 2- or 4-byte units,
// using only the RISC-V base length encoding (low two bits of each 16-bit
// half-word: 0b11 means a 32-bit-or-wider instruction, anything else is a
// 16-bit compressed instruction). This never inspects opcode, funct, or
// register fields, so it draws no instruction meaning from the bytes.
const walkUnits = (bytes, size, name) => {
  const units = []
  let offset = 0
  while (offset < size) {
    if (offset + 2 > size) throw new Error(`symbol ${name}: truncated half-word at offset ${offset}`)
    const half = bytes.readUInt16LE(offset)
    const isWide = (half & 0x3) === 0x3
    const length = isWide ? 4 : 2
    if (offset + length > size)
      throw new Error(`symbol ${name}: instruction at offset ${offset} extends past the symbol boundary`)
    const value = isWide ? bytes.readUInt32LE(offset) : half
    units.push({ offset, length, value })
    offset += length
  }
  if (offset !== size) throw new Error(`symbol ${name}: unit walk did not consume the exact declared size`)
  return units
}

// Resolve direct (JAL, branch) and AUIPC+JALR call/tail control-flow targets
// where supportable. Any other control transfer (register-indirect `ret`,
// `jr`, or a JALR not immediately preceded by a matching AUIPC) is left
// unresolved rather than guessed.
const resolveTargets = (units, symbolAddress) => {
  const targets = []
  for (let index = 0; index < units.length; index += 1) {
    const unit = units[index]
    if (unit.length !== 4) continue
    const word = unit.value
    const opcode = word & 0x7f
    const pc = symbolAddress + unit.offset
    if (opcode === OPCODE_JAL) {
      targets.push({ offset: unit.offset, format: 'J-type', address: pc + decodeJalImmediate(word) })
    } else if (opcode === OPCODE_BRANCH) {
      targets.push({ offset: unit.offset, format: 'B-type', address: pc + decodeBranchImmediate(word) })
    } else if (opcode === OPCODE_JALR) {
      const previous = index > 0 ? units[index - 1] : null
      if (previous && previous.length === 4 && (previous.value & 0x7f) === OPCODE_AUIPC &&
        rdField(previous.value) === rs1Field(word)) {
        const auipcResult = (symbolAddress + previous.offset) + decodeUtypeImmediate(previous.value)
        targets.push({ offset: unit.offset, format: 'auipc-pair', address: auipcResult + decodeItypeImmediate(word) })
      }
    }
  }
  return targets
}

const parseSections = (buffer, label) => {
  if (buffer.length < 64) throw new Error(`${label}: file is truncated: shorter than the ELF header`)
  if (!buffer.subarray(0, 4).equals(ELF_MAGIC)) throw new Error(`${label}: bad ELF magic`)
  const eiClass = buffer.readUInt8(4)
  const eiData = buffer.readUInt8(5)
  const eiVersion = buffer.readUInt8(6)
  if (eiClass !== ELFCLASS64) throw new Error(`${label}: unsupported ELF shape: not a 64-bit ELF (EI_CLASS)`)
  if (eiData !== ELFDATA2LSB) throw new Error(`${label}: unsupported ELF shape: not little-endian (EI_DATA)`)
  if (eiVersion !== 1) throw new Error(`${label}: unsupported ELF shape: unexpected EI_VERSION`)
  const eType = buffer.readUInt16LE(16)
  const eMachine = buffer.readUInt16LE(18)
  const eVersion = buffer.readUInt32LE(20)
  const eEntry = safeNumber(buffer.readBigUInt64LE(24), `${label}: e_entry`)
  const eShoff = safeNumber(buffer.readBigUInt64LE(40), `${label}: e_shoff`)
  const eShentsize = buffer.readUInt16LE(58)
  const eShnum = buffer.readUInt16LE(60)
  const eShstrndx = buffer.readUInt16LE(62)
  if (eType !== ET_EXEC) throw new Error(`${label}: unsupported ELF shape: not ET_EXEC`)
  if (eMachine !== EM_RISCV) throw new Error(`${label}: unsupported ELF shape: not EM_RISCV`)
  if (eVersion !== 1) throw new Error(`${label}: unsupported ELF shape: unexpected e_version`)
  if (eShentsize !== 64) throw new Error(`${label}: unsupported ELF shape: unexpected section header entry size`)
  if (eShnum === 0) throw new Error(`${label}: unsupported ELF shape: no section headers`)
  if (eShstrndx >= eShnum) throw new Error(`${label}: unsupported ELF shape: e_shstrndx out of range`)
  if (eShoff + eShnum * eShentsize > buffer.length)
    throw new Error(`${label}: file is truncated: section header table extends past end of file`)

  const sections = []
  for (let index = 0; index < eShnum; index += 1) {
    const base = eShoff + index * eShentsize
    const shName = buffer.readUInt32LE(base)
    const shType = buffer.readUInt32LE(base + 4)
    const shFlags = safeNumber(buffer.readBigUInt64LE(base + 8), `${label}: section ${index} sh_flags`)
    const shAddr = safeNumber(buffer.readBigUInt64LE(base + 16), `${label}: section ${index} sh_addr`)
    const shOffset = safeNumber(buffer.readBigUInt64LE(base + 24), `${label}: section ${index} sh_offset`)
    const shSize = safeNumber(buffer.readBigUInt64LE(base + 32), `${label}: section ${index} sh_size`)
    const shLink = buffer.readUInt32LE(base + 40)
    const shEntsize = safeNumber(buffer.readBigUInt64LE(base + 56), `${label}: section ${index} sh_entsize`)
    // Symbol containment, symbol overlap, and instruction addresses all add
    // to sh_addr, so the section's end must be exact as a Number as well.
    if (BigInt(shAddr) + BigInt(shSize) > MAX_SAFE)
      throw new Error(`${label}: section ${index} end address is out of the supported range`)
    if ((shFlags & SHF_COMPRESSED) !== 0)
      throw new Error(`${label}: compressed section ${index} is not a supported ELF shape`)
    if (shType !== SHT_NOBITS && shOffset + shSize > buffer.length)
      throw new Error(`${label}: file is truncated: section ${index} extends past end of file`)
    sections.push({ index, shName, shType, shFlags, shAddr, shOffset, shSize, shLink, shEntsize })
  }
  // Every section name this parser reads is resolved through the section-name
  // string table, so that table is validated before it is trusted rather than
  // being discovered accidentally inside readCString. e_shstrndx must name an
  // in-bounds, non-empty, NUL-terminated SHT_STRTAB with real file content;
  // a NOBITS, oversize, empty, or non-strtab index is a bounded refusal here.
  const shstrtab = sections[eShstrndx]
  if (shstrtab.shType === SHT_NOBITS)
    throw new Error(`${label}: unsupported ELF shape: e_shstrndx section ${eShstrndx} has no file content (NOBITS)`)
  if (shstrtab.shType !== SHT_STRTAB)
    throw new Error(`${label}: unsupported ELF shape: e_shstrndx section ${eShstrndx} is not SHT_STRTAB`)
  if (shstrtab.shSize === 0)
    throw new Error(`${label}: unsupported ELF shape: e_shstrndx section ${eShstrndx} is empty`)
  if (shstrtab.shOffset + shstrtab.shSize > buffer.length)
    throw new Error(`${label}: file is truncated: e_shstrndx section ${eShstrndx} extends past end of file`)
  if (buffer[shstrtab.shOffset + shstrtab.shSize - 1] !== 0)
    throw new Error(`${label}: unsupported ELF shape: e_shstrndx section ${eShstrndx} is not NUL-terminated`)
  for (const section of sections)
    section.name = readCString(buffer, shstrtab.shOffset, shstrtab.shSize, section.shName, `${label}: section ${section.index}`)
  return { sections, eEntry }
}

const parseSymbols = (buffer, label, sections) => {
  const symtabSections = sections.filter((section) => section.shType === SHT_SYMTAB)
  if (symtabSections.length !== 1)
    throw new Error(`${label}: unsupported ELF shape: expected exactly one SHT_SYMTAB section, found ${symtabSections.length}`)
  const [symtab] = symtabSections
  if (symtab.shEntsize !== 24)
    throw new Error(`${label}: unsupported ELF shape: unexpected symbol table entry size`)
  const strtab = sections[symtab.shLink]
  if (!strtab || strtab.shType !== SHT_STRTAB)
    throw new Error(`${label}: unsupported ELF shape: symbol table does not link a string table`)
  const symbolCount = symtab.shSize / symtab.shEntsize
  if (!Number.isInteger(symbolCount))
    throw new Error(`${label}: unsupported ELF shape: symbol table size is not a multiple of its entry size`)

  const matches = new Map(REQUIRED_SYMBOLS.map((name) => [name, []]))
  for (let index = 1; index < symbolCount; index += 1) { // entry 0 is always the null symbol
    const base = symtab.shOffset + index * symtab.shEntsize
    const stName = buffer.readUInt32LE(base)
    const stShndx = buffer.readUInt16LE(base + 6)
    const stValue = safeNumber(buffer.readBigUInt64LE(base + 8), `${label}: symbol ${index} st_value`)
    const stSize = safeNumber(buffer.readBigUInt64LE(base + 16), `${label}: symbol ${index} st_size`)
    const name = readCString(buffer, strtab.shOffset, strtab.shSize, stName, `${label}: symbol ${index}`)
    if (matches.has(name)) matches.get(name).push({ stShndx, stValue, stSize })
  }

  const symbols = []
  for (const name of REQUIRED_SYMBOLS) {
    const found = matches.get(name)
    if (found.length === 0) throw new Error(`${label}: missing required symbol ${name}`)
    if (found.length > 1) throw new Error(`${label}: multiply defined symbol ${name} (${found.length} definitions)`)
    const [symbol] = found
    if (symbol.stShndx === SHN_UNDEF) throw new Error(`${label}: symbol ${name} is undefined (SHN_UNDEF)`)
    if (symbol.stShndx >= SHN_LORESERVE)
      throw new Error(`${label}: symbol ${name} has an unsupported reserved section index`)
    if (symbol.stShndx >= sections.length) throw new Error(`${label}: symbol ${name} section index is out of range`)
    const section = sections[symbol.stShndx]
    if (section.shType === SHT_NOBITS) throw new Error(`${label}: symbol ${name} has no file content (NOBITS section)`)
    if ((section.shFlags & SHF_EXECINSTR) === 0) throw new Error(`${label}: symbol ${name} is not in an executable section`)
    if (symbol.stSize === 0) throw new Error(`${label}: symbol ${name} has zero size`)
    if (symbol.stValue % 4 !== 0) throw new Error(`${label}: symbol ${name} is not 4-byte aligned`)
    if (symbol.stValue < section.shAddr || symbol.stValue + symbol.stSize > section.shAddr + section.shSize)
      throw new Error(`${label}: symbol ${name} is out of range of its containing section`)
    const fileOffset = section.shOffset + (symbol.stValue - section.shAddr)
    if (fileOffset + symbol.stSize > buffer.length) throw new Error(`${label}: symbol ${name} extends past end of file`)
    const bytes = buffer.subarray(fileOffset, fileOffset + symbol.stSize)
    const units = walkUnits(bytes, symbol.stSize, name)
    const targets = resolveTargets(units, symbol.stValue)
    symbols.push({ name, address: symbol.stValue, size: symbol.stSize, units, targets })
  }

  const byAddress = [...symbols].sort((a, b) => a.address - b.address)
  for (let index = 1; index < byAddress.length; index += 1) {
    const previous = byAddress[index - 1]
    const current = byAddress[index]
    if (current.address < previous.address + previous.size)
      throw new Error(`${label}: symbols ${previous.name} and ${current.name} overlap`)
  }
  return { symbols, symbolCount }
}

// Canonical, build-path-independent identity of one image's loadable
// content. Every SHF_ALLOC section is recorded in section-header-table order
// as
//
//   <name>\0<sh_type>\0<sh_flags>\0<sh_addr>\0<sh_size>\0<content>\n
//
// with sh_type in decimal, sh_flags/sh_addr/sh_size in lower-case hex with a
// 0x prefix, and <content> the lower-case SHA-256 of that section's file
// bytes, or the literal `nobits` for SHT_NOBITS (a section that occupies
// address space but carries no file content). The record is prefixed by a
// schema line, the entry point, and the allocated-section count, and hashed
// as UTF-8. A non-allocated section -- every .debug_* section, .comment,
// .symtab, .strtab, .shstrtab, .riscv.attributes -- contributes nothing.
const ALLOC_IDENTITY_SCHEMA = 'be-r7-alloc-image-v1'

const allocIdentity = (buffer, sections, eEntry, label) => {
  const allocated = sections.filter((section) => (section.shFlags & SHF_ALLOC) !== 0)
  const rows = allocated.map((section) => ({
    name: section.name,
    type: section.shType,
    flags: hex(section.shFlags, 8),
    address: hex(section.shAddr, 8),
    size: section.shSize,
    sha256: section.shType === SHT_NOBITS
      ? 'nobits'
      : createHash('sha256')
        .update(buffer.subarray(section.shOffset, section.shOffset + section.shSize))
        .digest('hex')
  }))
  const canonical = [
    `${ALLOC_IDENTITY_SCHEMA}\n`,
    `entry=${hex(eEntry, 8)}\n`,
    `sections=${rows.length}\n`,
    ...rows.map((row) =>
      `${row.name}\0${row.type}\0${row.flags}\0${row.address}\0${hex(row.size, 8)}\0${row.sha256}\n`)
  ].join('')
  return {
    sha256: createHash('sha256').update(Buffer.from(canonical, 'utf8')).digest('hex'),
    sections: rows,
    fileBytes: rows.reduce((sum, row) => sum + (row.sha256 === 'nobits' ? 0 : row.size), 0),
    // NOBITS sizes are not bounded by the file, so this total can pass 2^53.
    memoryBytes: safeNumber(rows.reduce((sum, row) => sum + BigInt(row.size), 0n),
      `${label}: allocated memory-byte total`)
  }
}

// Parse one ELF64 image directly (no readelf/nm/objdump) and return the
// eleven scoped symbols' exact bytes, structural units, and resolved
// control-flow targets. Throws on any unsupported ELF shape, compressed
// section, truncated file, overlapping/multiply-defined/missing scoped
// symbol, or out-of-range address/size.
export const extractImage = (elfPath, label) => {
  const buffer = readFileSync(elfPath)
  const sha256 = createHash('sha256').update(buffer).digest('hex')
  const { sections, eEntry } = parseSections(buffer, label)
  const { symbols, symbolCount } = parseSymbols(buffer, label, sections)
  const alloc = allocIdentity(buffer, sections, eEntry, label)
  if (alloc.sections.length === 0) throw new Error(`${label}: image carries no allocated section`)
  return {
    schema: 'be-r7-exact-image-v1',
    toolchain: label,
    elf: {
      // Observed run identity of this exact file, not a reproducible
      // constant: see the header note on DW_AT_comp_dir.
      sha256,
      sizeBytes: buffer.length,
      // Build-path-independent identity of the loadable image. This is what
      // the proof pins.
      allocSchema: ALLOC_IDENTITY_SCHEMA,
      allocSha256: alloc.sha256,
      allocSectionCount: alloc.sections.length,
      allocFileBytes: alloc.fileBytes,
      allocMemoryBytes: alloc.memoryBytes,
      class: 64,
      dataEncoding: 'little-endian',
      type: 'EXEC',
      machine: 'EM_RISCV',
      entry: hex(eEntry, 8),
      sectionCount: sections.length,
      symbolTableEntries: symbolCount
    },
    allocSections: alloc.sections,
    symbols: symbols.map((symbol) => ({
      name: symbol.name,
      address: hex(symbol.address, 8),
      size: symbol.size,
      units: symbol.units.map((unit) => ({
        offset: unit.offset,
        length: unit.length,
        hex: hex(unit.value, unit.length * 2)
      })),
      targets: symbol.targets.map((target) => ({
        offset: target.offset,
        format: target.format,
        address: hex(target.address, 8)
      }))
    }))
  }
}

export const canonicalJson = (image) => `${JSON.stringify(image, null, 2)}\n`

const runExtraction = () => {
  mkdirSync(extractDir, { recursive: true })
  const gcc = extractImage(gccElfPath, 'gcc')
  const clang = extractImage(clangElfPath, 'clang')
  writeFileSync(resolve(extractDir, 'gcc.json'), canonicalJson(gcc))
  writeFileSync(resolve(extractDir, 'clang.json'), canonicalJson(clang))
  const unitCount = (image) => image.symbols.reduce((sum, symbol) => sum + symbol.units.length, 0)
  const targetCount = (image) => image.symbols.reduce((sum, symbol) => sum + symbol.targets.length, 0)
  process.stdout.write(
    `BE_R7_EXTRACT: PASS toolchains=2 symbols=${gcc.symbols.length + clang.symbols.length} ` +
    `units=${unitCount(gcc) + unitCount(clang)} targets=${targetCount(gcc) + targetCount(clang)} ` +
    `alloc-sections=${gcc.allocSections.length + clang.allocSections.length} ` +
    `output=build/r7/extract\n`
  )
}

// ---------------------------------------------------------------- self-test
//
// Focused rejection coverage for the ELF-shape hard-refusal list this
// extractor enforces: unsupported shape, compressed section, truncated
// file, an instruction straddling a symbol boundary, overlapping symbols,
// a multiply defined symbol, a missing symbol, and an out-of-range address
// or size, plus the allocated-image identity cases. It runs under `--self-test`
// in the `r7-check` stage, never inside the `r7-extract` recipe the accepted
// plan names: extraction stays exactly the accepted sequence, and the rejection
// coverage is checked separately.
const NOP_WORD = Buffer.from([0x13, 0x00, 0x00, 0x00]) // addi x0,x0,0
const COMPRESSED_UNIT = Buffer.from([0x01, 0x00]) // low bits != 0b11: 16-bit unit
// A non-allocated PROGBITS section standing in for the real images'
// .debug_* sections: bytes that belong to the file but never to the loadable
// image. The self-test mutates it to prove the pinned allocated-image
// identity does not move when a debug byte does.
const DEBUG_FIXTURE_BYTES = Buffer.from('/build/path/placeholder\0', 'latin1')

const buildSyntheticElf = () => {
  const textOffset = 64
  const slot = 16
  const parts = []
  for (let index = 0; index < REQUIRED_SYMBOLS.length; index += 1) {
    if (index === REQUIRED_SYMBOLS.length - 1) {
      parts.push(NOP_WORD, NOP_WORD, COMPRESSED_UNIT) // one deliberately mixed-width symbol
    } else {
      parts.push(NOP_WORD, NOP_WORD, Buffer.alloc(slot - 8))
    }
  }
  const text = Buffer.concat(parts)
  const textSize = (REQUIRED_SYMBOLS.length - 1) * slot + 10
  if (text.length !== textSize) throw new Error('self-test: synthetic .text layout is inconsistent')

  const strtabParts = [Buffer.from([0])]
  const nameOffsets = new Map()
  for (const name of REQUIRED_SYMBOLS) {
    nameOffsets.set(name, strtabParts.reduce((sum, part) => sum + part.length, 0))
    strtabParts.push(Buffer.from(`${name}\0`, 'latin1'))
  }
  const strtab = Buffer.concat(strtabParts)

  const sectionNames = ['', '.text', '.symtab', '.strtab', '.shstrtab', '.debug_fixture']
  const shstrtabParts = [Buffer.from([0])]
  const sectionNameOffsets = new Map()
  for (const name of sectionNames.slice(1)) {
    sectionNameOffsets.set(name, shstrtabParts.reduce((sum, part) => sum + part.length, 0))
    shstrtabParts.push(Buffer.from(`${name}\0`, 'latin1'))
  }
  const shstrtab = Buffer.concat(shstrtabParts)

  const strtabOffset = textOffset + text.length
  const symtabOffset = strtabOffset + strtab.length

  const symtabEntryCount = 1 + REQUIRED_SYMBOLS.length
  const symtab = Buffer.alloc(symtabEntryCount * 24)
  const symbolFieldOffsets = new Map()
  for (let index = 0; index < REQUIRED_SYMBOLS.length; index += 1) {
    const name = REQUIRED_SYMBOLS[index]
    const entryBase = (index + 1) * 24
    const address = 0x1000 + index * slot
    const size = index === REQUIRED_SYMBOLS.length - 1 ? 10 : 8
    symtab.writeUInt32LE(nameOffsets.get(name), entryBase)
    symtab.writeUInt8((1 << 4) | 2, entryBase + 4) // STB_GLOBAL | STT_FUNC
    symtab.writeUInt8(0, entryBase + 5)
    symtab.writeUInt16LE(1, entryBase + 6) // section index 1 == .text
    symtab.writeBigUInt64LE(BigInt(address), entryBase + 8)
    symtab.writeBigUInt64LE(BigInt(size), entryBase + 16)
    symbolFieldOffsets.set(name, {
      stShndx: symtabOffset + entryBase + 6,
      stValue: symtabOffset + entryBase + 8,
      stSize: symtabOffset + entryBase + 16,
      entryBase: symtabOffset + entryBase
    })
  }

  const shstrtabOffset = symtabOffset + symtab.length
  const debugOffset = shstrtabOffset + shstrtab.length
  const shOffsetStart = debugOffset + DEBUG_FIXTURE_BYTES.length

  const sections = [
    { name: '', type: 0, flags: 0n, addr: 0n, offset: 0n, size: 0n, link: 0, entsize: 0n },
    { name: '.text', type: 1, flags: 0x6n, addr: 0x1000n, offset: BigInt(textOffset), size: BigInt(text.length), link: 0, entsize: 0n },
    { name: '.symtab', type: 2, flags: 0n, addr: 0n, offset: BigInt(symtabOffset), size: BigInt(symtab.length), link: 3, entsize: 24n },
    { name: '.strtab', type: 3, flags: 0n, addr: 0n, offset: BigInt(strtabOffset), size: BigInt(strtab.length), link: 0, entsize: 0n },
    { name: '.shstrtab', type: 3, flags: 0n, addr: 0n, offset: BigInt(shstrtabOffset), size: BigInt(shstrtab.length), link: 0, entsize: 0n },
    { name: '.debug_fixture', type: 1, flags: 0n, addr: 0n, offset: BigInt(debugOffset), size: BigInt(DEBUG_FIXTURE_BYTES.length), link: 0, entsize: 0n }
  ]
  const shTable = Buffer.alloc(sections.length * 64)
  const sectionFieldOffsets = []
  for (const [index, section] of sections.entries()) {
    const base = index * 64
    shTable.writeUInt32LE(section.name === '' ? 0 : sectionNameOffsets.get(section.name), base)
    shTable.writeUInt32LE(section.type, base + 4)
    shTable.writeBigUInt64LE(section.flags, base + 8)
    shTable.writeBigUInt64LE(section.addr, base + 16)
    shTable.writeBigUInt64LE(section.offset, base + 24)
    shTable.writeBigUInt64LE(section.size, base + 32)
    shTable.writeUInt32LE(section.link, base + 40)
    shTable.writeUInt32LE(0, base + 44)
    shTable.writeBigUInt64LE(1n, base + 48)
    shTable.writeBigUInt64LE(section.entsize, base + 56)
    sectionFieldOffsets.push({
      flags: shOffsetStart + base + 8,
      addr: shOffsetStart + base + 16,
      offset: shOffsetStart + base + 24,
      size: shOffsetStart + base + 32,
      type: shOffsetStart + base + 4
    })
  }

  const header = Buffer.alloc(64)
  ELF_MAGIC.copy(header, 0)
  header.writeUInt8(ELFCLASS64, 4)
  header.writeUInt8(ELFDATA2LSB, 5)
  header.writeUInt8(1, 6)
  header.writeUInt16LE(ET_EXEC, 16)
  header.writeUInt16LE(EM_RISCV, 18)
  header.writeUInt32LE(1, 20)
  header.writeBigUInt64LE(0x1000n, 24) // e_entry
  header.writeBigUInt64LE(0n, 32) // e_phoff
  header.writeBigUInt64LE(BigInt(shOffsetStart), 40) // e_shoff
  header.writeUInt32LE(0, 48)
  header.writeUInt16LE(64, 52)
  header.writeUInt16LE(0, 54)
  header.writeUInt16LE(0, 56)
  header.writeUInt16LE(64, 58) // e_shentsize
  header.writeUInt16LE(sections.length, 60) // e_shnum
  header.writeUInt16LE(4, 62) // e_shstrndx

  const buffer = Buffer.concat([header, text, strtab, symtab, shstrtab, DEBUG_FIXTURE_BYTES, shTable])
  return { buffer, symbolFieldOffsets, sectionFieldOffsets, shOffsetStart, textOffset, debugOffset }
}

const expectRejected = (label, mutate) => {
  const { buffer } = buildSyntheticElf()
  const mutated = mutate(buffer) ?? buffer
  mkdirSync(selfTestScratchRoot, { recursive: true })
  const scratch = mkdtempSync(resolve(selfTestScratchRoot, 'run-'))
  try {
    const path = resolve(scratch, 'image.elf')
    writeFileSync(path, mutated)
    let threw = false
    try {
      extractImage(path, 'self-test')
    } catch {
      threw = true
    }
    if (!threw) throw new Error(`self-test: mutation '${label}' was not rejected`)
  } finally {
    rmSync(scratch, { recursive: true, force: true })
  }
}

const runSelfTest = () => {
  mkdirSync(selfTestScratchRoot, { recursive: true })
  const scratch = mkdtempSync(resolve(selfTestScratchRoot, 'run-'))
  let identityCases = 0
  try {
    const { buffer, textOffset, debugOffset } = buildSyntheticElf()
    const baselinePath = resolve(scratch, 'baseline.elf')
    writeFileSync(baselinePath, buffer)
    const baseline = extractImage(baselinePath, 'self-test')
    if (baseline.symbols.length !== REQUIRED_SYMBOLS.length)
      throw new Error('self-test: baseline did not extract all required symbols')
    const mixed = baseline.symbols[baseline.symbols.length - 1]
    if (mixed.units.length !== 3 || mixed.units[2].length !== 2)
      throw new Error('self-test: baseline did not preserve the mixed-width trailing unit')
    if (JSON.stringify(extractImage(baselinePath, 'self-test')) !== JSON.stringify(baseline))
      throw new Error('self-test: baseline extraction is not deterministic')

    // The allocated-image identity must cover exactly the SHF_ALLOC
    // sections: the synthetic image allocates .text and nothing else.
    if (baseline.allocSections.length !== 1 || baseline.allocSections[0].name !== '.text')
      throw new Error('self-test: allocated-section table is not exactly the allocated sections')
    if (baseline.elf.allocSectionCount !== 1 || baseline.elf.allocFileBytes !== baseline.allocSections[0].size)
      throw new Error('self-test: allocated byte totals disagree with the allocated-section table')
    if (!/^[0-9a-f]{64}$/.test(baseline.elf.allocSha256))
      throw new Error('self-test: allocated-image identity is not a SHA-256 digest')
    identityCases += 1

    // The root-cause regression this pair pins: a byte that lives only in a
    // non-allocated (debug) section changes the whole-file digest and must
    // not change the pinned allocated-image identity, because that is
    // exactly how one correct build at another worktree path differs from
    // another. `-g3 -gdwarf-4` writes the absolute build directory into
    // .debug_str, so the file digest is a run identity and the allocated
    // identity is the reproducible one.
    const debugMutated = Buffer.from(buffer)
    debugMutated[debugOffset] = debugMutated[debugOffset] ^ 0xff
    const debugPath = resolve(scratch, 'debug-mutated.elf')
    writeFileSync(debugPath, debugMutated)
    const debugImage = extractImage(debugPath, 'self-test')
    if (debugImage.elf.sha256 === baseline.elf.sha256)
      throw new Error('self-test: a mutated debug byte did not change the whole-file digest')
    if (debugImage.elf.allocSha256 !== baseline.elf.allocSha256)
      throw new Error('self-test: a mutated non-allocated byte moved the allocated-image identity')
    if (JSON.stringify(debugImage.symbols) !== JSON.stringify(baseline.symbols))
      throw new Error('self-test: a mutated non-allocated byte moved the extracted symbol bytes')
    identityCases += 1

    // The converse: an allocated byte must move the pinned identity.
    const textMutated = Buffer.from(buffer)
    textMutated[textOffset] = textMutated[textOffset] ^ 0xff
    const textPath = resolve(scratch, 'text-mutated.elf')
    writeFileSync(textPath, textMutated)
    const textImage = extractImage(textPath, 'self-test')
    if (textImage.elf.allocSha256 === baseline.elf.allocSha256)
      throw new Error('self-test: a mutated allocated byte did not move the allocated-image identity')
    identityCases += 1
  } finally {
    rmSync(scratch, { recursive: true, force: true })
  }

  const { symbolFieldOffsets, sectionFieldOffsets } = buildSyntheticElf()
  const firstSymbol = symbolFieldOffsets.get(REQUIRED_SYMBOLS[0])
  const secondSymbol = symbolFieldOffsets.get(REQUIRED_SYMBOLS[1])
  const textSection = sectionFieldOffsets[1]
  const shstrtabSection = sectionFieldOffsets[4]

  const mutations = [
    ['bad-magic', (buffer) => { buffer[0] = 0x00 }],
    ['wrong-class', (buffer) => { buffer[4] = 1 }],
    ['wrong-endian', (buffer) => { buffer[5] = 2 }],
    ['wrong-machine', (buffer) => { buffer.writeUInt16LE(0x3e, 18) }],
    ['wrong-type', (buffer) => { buffer.writeUInt16LE(3, 16) }],
    ['truncated-file', (buffer) => buffer.subarray(0, buffer.length - 16)],
    ['missing-symbol', (buffer) => { buffer.writeUInt32LE(0, firstSymbol.entryBase) }], // rename st_name to the empty string so the required name is absent
    ['undefined-symbol', (buffer) => { buffer.writeUInt16LE(0, firstSymbol.stShndx) }],
    ['reserved-shndx', (buffer) => { buffer.writeUInt16LE(0xfff1, firstSymbol.stShndx) }],
    ['zero-size-symbol', (buffer) => { buffer.writeBigUInt64LE(0n, firstSymbol.stSize) }],
    ['misaligned-symbol', (buffer) => {
      buffer.writeBigUInt64LE(BigInt(0x1000 + 1), firstSymbol.stValue)
    }],
    ['out-of-range-symbol', (buffer) => {
      buffer.writeBigUInt64LE(BigInt(0x1000 + 0x100000), firstSymbol.stValue)
    }],
    ['truncated-instruction', (buffer) => { buffer.writeBigUInt64LE(6n, firstSymbol.stSize) }],
    ['overlapping-symbols', (buffer) => {
      buffer.writeBigUInt64LE(buffer.readBigUInt64LE(firstSymbol.stValue), secondSymbol.stValue)
    }],
    ['multiply-defined-symbol', (buffer) => {
      // Give the second required symbol's entry the first symbol's name offset.
      const nameOffset = buffer.readUInt32LE(firstSymbol.entryBase)
      buffer.writeUInt32LE(nameOffset, secondSymbol.entryBase)
    }],
    ['nobits-section', (buffer) => { buffer.writeUInt32LE(SHT_NOBITS, textSection.type) }],
    ['non-executable-section', (buffer) => { buffer.writeBigUInt64LE(0x2n, textSection.flags) }],
    ['compressed-section', (buffer) => {
      buffer.writeBigUInt64LE(buffer.readBigUInt64LE(textSection.flags) | BigInt(SHF_COMPRESSED), textSection.flags)
    }],
    // e_shstrndx attacks: the section-name string table must be a real,
    // in-bounds, NUL-terminated SHT_STRTAB before any name is read from it.
    ['shstrndx-not-strtab', (buffer) => { buffer.writeUInt32LE(SHT_SYMTAB, shstrtabSection.type) }],
    ['shstrndx-nobits', (buffer) => { buffer.writeUInt32LE(SHT_NOBITS, shstrtabSection.type) }],
    ['shstrndx-empty', (buffer) => { buffer.writeBigUInt64LE(0n, shstrtabSection.size) }],
    ['shstrndx-oversize', (buffer) => {
      buffer.writeBigUInt64LE(BigInt(buffer.length), shstrtabSection.size)
    }],
    ['shstrndx-unterminated', (buffer) => {
      buffer.writeBigUInt64LE(buffer.readBigUInt64LE(shstrtabSection.size) - 1n, shstrtabSection.size)
    }],
    ['shstrndx-points-at-text', (buffer) => { buffer.writeUInt16LE(1, 62) }]
  ]
  for (const [label, mutate] of mutations) expectRejected(label, mutate)
  process.stdout.write(
    `BE_R7_EXTRACT_SELF_TEST: PASS baseline=accepted mutations=${mutations.length} all-rejected=yes ` +
    `identity-cases=${identityCases} alloc-identity=build-path-independent\n`
  )
}

const invokedDirectly = process.argv[1] && resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url))
if (invokedDirectly) {
  try {
    if (process.argv.includes('--self-test')) runSelfTest()
    else runExtraction()
  } catch (error) {
    process.stderr.write(`extract-exact-image: ${error.message}\n`)
    process.exitCode = 1
  }
}
