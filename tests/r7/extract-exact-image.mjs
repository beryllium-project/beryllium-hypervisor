// Direct ELF64 extractor for the eleven R7 exact-byte symbols named by
// planning/single-hart-runtime-r7-plan.md ("Exact linked-byte scope"). This
// script parses the final GCC/GNU ld and Clang/lld R5 images itself: no
// readelf, nm, or objdump. tests/r7/check-disassembly.sh independently
// recovers the same address and word stream with the locked GNU objdump, so
// this extractor is never trusted alone for the bytes it reports.
//
// Eight of the eleven symbols live in arch/riscv/be/r5-trap.S, which sets
// `.option norvc` and is therefore pure 32-bit words throughout. The three
// be_r3_arch_* symbols live in arch/riscv/be/privileged.S, which carries no
// such directive, so GCC and Clang both legitimately compress some of their
// leaf `ret`/`li rd,0` sequences into standard 16-bit RVC instructions (both
// toolchains compress the identical offsets). This extractor therefore
// records each symbol as an ordered sequence of variable-width raw units (2
// or 4 bytes), using only the RISC-V base instruction-length encoding (the
// low two bits of each 16-bit half-word) to find unit boundaries. That is a
// structural framing fact drawn directly from the ISA's fixed length
// encoding, not an instruction decode: this extractor still asserts no
// instruction meaning, and every accepted image must still satisfy the
// plan's own hard-refusal list at the ELF-container level -- an unsupported
// ELF shape, a compressed (SHF_COMPRESSED) section, a truncated file, an
// instruction that would straddle a symbol boundary, overlapping or
// multiply defined scoped symbols, and any address or size outside its
// containing section.
//
// Two image identities are recorded, and they are deliberately different
// kinds of fact:
//
//   elf.sha256 / elf.sizeBytes   the whole ELF *file*. The accepted R5
//                                recipes compile with `-g3 -gdwarf-4` and no
//                                `-fdebug-prefix-map`, so every object
//                                carries DW_AT_comp_dir -- the absolute path
//                                of the building worktree's tests/r5. Two
//                                correct builds of identical sources at
//                                different paths therefore produce different
//                                .debug_str/.debug_info bytes (and, for
//                                Clang, different .debug_aranges bytes and
//                                shifted `$d` mapping symbols). These two
//                                values are an *observed run identity* of
//                                one build in one location. Nothing may pin
//                                them as a reproducible constant.
//
//   elf.allocSha256 and the      the *loadable image*: every SHF_ALLOC
//   elf.allocSections table      section's name, type, flags, address, size,
//                                and content. This is exactly what the
//                                loader maps and the hart executes, it
//                                contains no build path, and it is
//                                byte-identical across worktrees. This is
//                                the identity the proof pins.
//
// The canonicalisation is fixed and documented so an independent reader can
// recompute it: see allocIdentity below.
