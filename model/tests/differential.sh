# The differential check (MVP M3, work package M3-5; planning/mvp-m3-plan.md,
# "Differential checking (M3-5)", Q8, Q9, and its review packet's erratum
# 10): security model v1's analyses A1 to A8, computed three ways on the
# generator's instances and seeded mutations, compared verdict by verdict.
#
#   oracle  Policy.v's verdicts, by vm_compute, on the generated Instances.v
#           terms: a generated Oracle.v compiled against the checked proof
#   model   tools/policy-run.c on the same generator's C data; the GCC and
#           Clang outputs must be identical
#   mvp     mvp/tools/policy-check.py, from the same commit, on the
#           generator's MVP files, through the command line mvp/Makefile uses
#
# Instances 2 and 3 and their mutations compare three ways; Instance 1, its
# Model 0.2 projection, and Instance 1's mutations have no MVP form and
# compare two ways, the oracle and the model's checker. A comparison is one
# pair of checkers on one instance or mutation, all eight verdicts equal;
# not-run (absent from the oracle's list) follows an A1 failure. Every
# instance must pass every analysis, and every mutation must fail exactly
# the analyses model/fixtures/mutations.json names for it. Agreement is the
# claim: neither host checker is thereby proved to be the Rocq function.
# Run after make proof and policy-run; it reads only the repository and
# build/, writes build/model/differential/, and needs no network.
set -eu

model=$(CDPATH= cd -- "$(dirname "$0")/.." && pwd)
repository=$(CDPATH= cd -- "$model/.." && pwd)
build=$repository/build/model
policy=$build/policy
checked=$build/proof/checked
output=$build/differential
ROCQ=${ROCQ:-rocq}

fail()
{
	printf 'BE_MODEL_DIFFERENTIAL: FAIL %s\n' "$*"
	exit 1
}

for file in "$policy/index.json" "$policy/Instances.v" \
	"$build/proof/instances-source.txt" "$checked/Policy.vo" \
	"$checked/Instances.vo" "$build/host/gcc/policy-run" \
	"$build/host/clang/policy-run"; do
	[ -e "$file" ] || fail "$file is missing: run make -C model proof policy-run"
done

# The oracle's module Instances must be the generator's file, which now
# carries the mutations, not proof/InstancesSample.v (M3-3's stand-in);
# and it defines exactly the four instances and the mutation list.
read -r kind _ <"$build/proof/instances-source.txt"
[ "$kind" = generated ] &&
	cmp -s "$build/proof/instances/Instances.v" "$policy/Instances.v" ||
	fail 'the proof did not compile the generated Instances.v'
instances=$(sed -n 's/^Definition \([A-Za-z0-9_]*\) .*/\1/p' \
	"$policy/Instances.v" | tr '\n' ' ')
[ "$instances" = 'instance1 instance2 instance3 instance1_m02 mutations ' ] ||
	fail "Instances.v defines $instances"

rm -rf "$output"
mkdir -p "$output/mvp"

# policy-run's status says whether the instances pass, which the comparison
# below checks verdict by verdict for every checker.
"$build/host/gcc/policy-run" >"$output/policy-run.gcc.txt" || :
"$build/host/clang/policy-run" >"$output/policy-run.clang.txt" || :
cmp -s "$output/policy-run.gcc.txt" "$output/policy-run.clang.txt" ||
	fail 'the GCC and Clang builds of policy-run print different verdicts'

tag=0
list=
for name in ${instances% mutations }; do
	list="$list${list:+; }($tag, verdicts $name)"
	tag=$((tag + 1))
done
cat >"$output/Oracle.v" <<EOF
(* SPDX-License-Identifier: GPL-3.0-only *)
(*
 * Copyright (C) 2026 James Morris <jamorris@linux.microsoft.com>
 *)

(* Generated by model/tests/differential.sh; do not edit. *)

Require Import Policy Instances.
Import ListNotations.

Eval vm_compute in [$list].
Eval vm_compute in map (fun entry => (fst entry, verdicts (snd entry))) mutations.
EOF
"$ROCQ" compile -q -R "$checked" '' -o "$output/Oracle.vo" \
	"$output/Oracle.v" >"$output/oracle.log" 2>&1 ||
	fail "the oracle did not compile: see $output/oracle.log"

# The generator writes MVP files only for the MVP-shaped instances and
# mutations; a refused input writes no report, which is a failure below.
# anchor's --kernel and --dtb are not passed: they add only the
# measurement, which no analysis reads.
for directory in "$policy"/instances/* "$policy"/mutations/*; do
	[ -d "$directory" ] || continue
	name=${directory##*/}
	python3 -B "$repository/mvp/tools/policy-check.py" \
		--scenario "$directory" \
		--layout "$repository/mvp/src/mvp-layout.h" \
		--report "$output/mvp/$name.json" \
		>"$output/mvp/$name.txt" 2>&1 || :
done

node - "$repository" "$policy" "$model/fixtures/mutations.json" "$output" \
	<<'EOF'
const fs = require('fs')
const path = require('path')
const [repository, policy, specPath, output] = process.argv.slice(2)
const ANALYSES = ['A1', 'A2', 'A3', 'A4', 'A5', 'A6', 'A7', 'A8']
const RESULTS = ['pass', 'fail', 'not-run']
const table = []
const read = (file) => fs.readFileSync(file, 'utf8')
const finish = (line, status) => {
  table.push(line)
  fs.writeFileSync(path.join(output, 'differential.txt'), `${table.join('\n')}\n`)
  console.log(line)
  process.exit(status)
}
const fail = (message) => finish(`BE_MODEL_DIFFERENTIAL: FAIL ${message}`, 1)

// The pinned set: the generator's, at least Q8's 64, each entry's failing
// set nonempty, A1 alone or A2 to A8 in order, with its claim (S1 H39).
const index = JSON.parse(read(path.join(policy, 'index.json')))
const spec = JSON.parse(read(specPath))
const count = index.mutations.length
if (
  spec.schema !== 'be-model-policy-mutations-v1' ||
  spec.seed !== index.seed ||
  spec.count !== count ||
  spec.mutations.length !== count ||
  count < 64
) {
  fail(`the set is not the generator's pinned ${spec.count} of at least 64 (${count} generated)`)
}
spec.mutations.forEach((m, k) => {
  const fails = m.fails
  const generated = index.mutations[k]
  if (
    !Array.isArray(fails) ||
    fails.length === 0 ||
    fails.join() !== ANALYSES.filter((a) => fails.includes(a)).join() ||
    (fails.includes('A1') && fails.length > 1) ||
    typeof m.claim !== 'string' ||
    m.claim === '' ||
    generated.name !== `mutation${k}` ||
    generated.instance !== m.instance ||
    generated.defect !== (m.defect ?? 'explicit')
  ) {
    fail(`mutation${k}: its fails, claim, or generated entry is not well formed`)
  }
})
table.push(`BE_MODEL_DIFFERENTIAL_SET schema=${spec.schema} seed=${spec.seed} count=${count}`)

// The instances' MVP files are the MVP's own scenario files.
for (const i of index.instances.filter((x) => x.mvp)) {
  for (const file of ['policy.te', 'scenario.json']) {
    const copy = fs.readFileSync(path.join(policy, i.mvp, file))
    if (!copy.equals(fs.readFileSync(path.join(repository, i.source, file)))) {
      fail(`${i.name}'s ${file} is not ${i.source}'s`)
    }
  }
}

// The oracle: two printed lists of (tag, verdicts), the instances tagged
// in Oracle.v's order and the mutations by their index.
const tags = [...read(path.join(output, 'Oracle.v')).matchAll(/\((\d+), verdicts (\w+)\)/g)]
const evaluated = tags.map(([, k, name]) => `${k}:${name}`).join()
if (evaluated !== index.instances.map((i, k) => `${k}:${i.name}`).join()) {
  fail("Oracle.v's instances are not the generator's")
}
const blocks = read(path.join(output, 'oracle.log'))
  .replace(/\s+/g, '')
  .split(':list(nat*list(nat*bool))')
if (blocks.length !== 3 || blocks[2] !== '') {
  fail('the oracle did not print exactly its two verdict lists')
}
const oracle = blocks.slice(0, 2).map((block, which) => {
  const body = /^=\[(.*)\]$/.exec(block)?.[1] ?? '#'
  const entry = /\((\d+),\[((?:\(\d+,(?:true|false)\);?)*)\]\);?/y
  const out = []
  for (let found = entry.exec(body); found; found = entry.exec(body)) {
    const pairs = [...found[2].matchAll(/\((\d+),(true|false)\)/g)]
    const listed = pairs.map(([, n, ok]) => `${n}${ok}`).join()
    const vector =
      listed === '1false'
        ? ['fail', ...Array(7).fill('not-run')]
        : pairs.length === 8 && pairs.every(([, n], i) => Number(n) === i + 1)
          ? pairs.map(([, , ok]) => (ok === 'true' ? 'pass' : 'fail'))
          : null
    out.push([Number(found[1]), vector])
    if (entry.lastIndex === body.length) break
  }
  const expected = which === 0 ? index.instances.length : count
  const consumed = entry.lastIndex === body.length
  if (!consumed || out.length !== expected || out.some(([k], i) => k !== i)) {
    fail(`the oracle's ${which === 0 ? 'instance' : 'mutation'} list does not parse`)
  }
  return out.map(([, vector]) => vector)
})

// The model's checker: one BE_POLICY_VERDICT line per instance and mutation.
const model = new Map()
for (const line of read(path.join(output, 'policy-run.gcc.txt')).split('\n')) {
  const found = /^BE_POLICY_VERDICT name=(\w+) (.*) identity=0x[0-9a-f]{16}$/.exec(line)
  if (found) {
    const words = found[2].split(' ')
    const ok = words.length === 8 && words.every((w, i) => w.startsWith(`${ANALYSES[i]}=`))
    model.set(found[1], ok ? words.map((w) => w.slice(3)) : null)
  }
}

// The MVP checker: its authority report's checks, A1 to A8 in order.
const mvp = (name) => {
  const report = path.join(output, 'mvp', `${name}.json`)
  if (!fs.existsSync(report)) {
    const said = read(path.join(output, 'mvp', `${name}.txt`)).trim()
    fail(`${name}: the MVP checker wrote no report: ${said}`)
  }
  const checks = JSON.parse(read(report)).checks
  return Array.isArray(checks) &&
    checks.length === 8 &&
    checks.every((c, i) => c.analysis === ANALYSES[i])
    ? checks.map((c) => c.result)
    : null
}

const entities = [
  ...index.instances.map((i, k) => ({
    ...i,
    base: i.name,
    defect: 'instance',
    fails: [],
    oracle: oracle[0][k],
  })),
  ...index.mutations.map((m, k) => ({
    ...m,
    base: m.instance,
    fails: spec.mutations[k].fails,
    oracle: oracle[1][k],
  })),
]
const shaped = entities.filter((e) => e.mvp)
if (model.size !== entities.length || shaped.some((e) => path.basename(e.mvp) !== e.name)) {
  fail("the model's checker did not judge exactly the generated instances and mutations")
}

// Each well-formed vector: A1 failing and the rest not-run, or A1 passing
// and the rest judged.
const formed = (v) =>
  Array.isArray(v) &&
  v.length === 8 &&
  v.every((r) => RESULTS.includes(r)) &&
  (v[0] === 'fail'
    ? v.slice(1).every((r) => r === 'not-run')
    : v[0] === 'pass' && v.slice(1).every((r) => r !== 'not-run'))
const failing = (v) => ANALYSES.filter((a, i) => v[i] === 'fail').join(',') || 'none'
let threeWay = 0
let twoWay = 0
let comparisons = 0
for (const e of entities) {
  const verdicts = [
    ['oracle', e.oracle],
    ['model', model.get(e.name)],
    ...(e.mvp ? [['mvp', mvp(e.name)]] : []),
  ]
  const shown = (v) => (v ? ANALYSES.map((a, i) => `${a}=${v[i]}`).join(' ') : 'malformed')
  const all = verdicts.map(([who, v]) => `${who} ${shown(v)}`).join('; ')
  const what = `${e.name} (${e.base}, ${e.defect})`
  for (const [who, v] of verdicts) {
    if (!formed(v)) fail(`${what}: the ${who} verdicts are malformed; ${all}`)
  }
  for (let i = 0; i < verdicts.length; i += 1) {
    for (let j = i + 1; j < verdicts.length; j += 1) {
      comparisons += 1
      if (verdicts[i][1].join() !== verdicts[j][1].join()) {
        fail(`${what}: ${verdicts[i][0]} and ${verdicts[j][0]} disagree; ${all}`)
      }
    }
  }
  const expected = e.fails.join(',') || 'none'
  if (failing(e.oracle) !== expected) {
    fail(`${what}: fails ${failing(e.oracle)}, not the expected ${expected}; ${all}`)
  }
  threeWay += e.mvp ? 1 : 0
  twoWay += e.mvp ? 0 : 1
  table.push(
    `BE_MODEL_DIFFERENTIAL_ENTRY name=${e.name} instance=${e.base} defect=${e.defect} ` +
      `way=${verdicts.length} expected=${expected} ` +
      verdicts.map(([who, v]) => `${who}=${failing(v)}`).join(' '),
  )
}
const judged = fs.readdirSync(path.join(output, 'mvp')).filter((f) => f.endsWith('.json'))
if (judged.length !== shaped.length) {
  fail('the MVP checker judged a file the generator did not write for it')
}
finish(
  `BE_MODEL_DIFFERENTIAL: PASS instances=${index.instances.length} mutations=${count} ` +
    `three_way=${threeWay} two_way=${twoWay} comparisons=${comparisons}`,
  0,
)
EOF
